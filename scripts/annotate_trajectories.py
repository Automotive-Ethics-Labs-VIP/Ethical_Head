"""
Trajectory Annotation Interface (CLI)
=====================================
This script provides an interactive Command Line Interface (CLI) for the "Annotation" 
phase of the RLHF pipeline.

It loads the unannotated trajectory pairs generated by `collect_trajectories.py`. 
Since it operates in a terminal, it parses the raw 40-dimensional state vectors into
human-readable statistical summaries (e.g., average speed, max speed, and counts of
actions taken like braking or swerving).

The human annotator reads these summaries and inputs their preference (0 for Trajectory A, 
1 for Trajectory B). The script immediately saves these choices using the `PreferenceDataset` 
manager so they can be used to train the Reward Model.

Usage:
    python scripts/annotate_trajectories.py
    
Inputs:
    Reads from `data/unannotated_pairs.json`
    
Outputs:
    Appends labeled preferences to `data/human_preferences.json`
"""

import sys
from pathlib import Path
import json
import argparse
import numpy as np

# Add project root to Python path
project_root = Path(__file__).parent.parent
sys.path.insert(0, str(project_root))

from data.preference_dataset import PreferenceDataset

ACTION_MAP = {
    0: "maintain_course",
    1: "brake_hard",
    2: "swerve_left",
    3: "swerve_right",
    4: "accelerate"
}

def summarize_trajectory(states, actions):
    """
    Creates a human-readable summary of a trajectory from state/action tensors.
    Without CARLA video, we rely on state vector metrics.
    """
    states = np.array(states)
    
    # Example state indexing based on proposal:
    # 0: v_ego
    # 1: n_passengers
    # 2: lane_position
    # 3: delta_v
    # 4-6: ped counts
    
    avg_speed = np.mean(states[:, 0])
    max_speed = np.max(states[:, 0])
    
    # Action breakdown
    action_counts = {name: 0 for name in ACTION_MAP.values()}
    for a in actions:
        action_counts[ACTION_MAP.get(a, "unknown")] += 1
        
    summary = f"""    Length: {len(actions)} steps
    Speed (Avg/Max): {avg_speed:.1f} / {max_speed:.1f}
    Actions Taken: """
    
    parts = []
    for action_name, count in action_counts.items():
        if count > 0:
            parts.append(f"{count}x {action_name}")
    
    summary += ", ".join(parts)
    return summary

def annotate_cli(input_file="data/unannotated_pairs.json", output_file="data/human_preferences.json", annotator_id="human_1"):
    """
    Interactive CLI for annotating trajectory pairs.
    """
    input_path = project_root / input_file
    if not input_path.exists():
        print(f"Error: Could not find unannotated pairs at {input_path}")
        print("Run 'python scripts/collect_trajectories.py' first.")
        return
        
    with open(input_path, 'r') as f:
        unannotated_pairs = json.load(f)
        
    dataset = PreferenceDataset(filepath=project_root / output_file)
    
    print("\n" + "="*50)
    print("🚗 AEL ETHICAL ALIGNMENT ANNOTATION INTERFACE 🚗")
    print("="*50)
    print(f"Loaded {len(unannotated_pairs)} pairs to annotate.")
    print("Keys: [0] = Prefer A, [1] = Prefer B, [s] = Skip, [q] = Quit")
    print("="*50 + "\n")
    
    pairs_annotated = 0
    
    try:
        for idx, pair in enumerate(unannotated_pairs):
            print(f"\n--- Scenario {idx+1}/{len(unannotated_pairs)} [{pair['id']}] ---")
            
            # Print summaries
            print("\nTrajectory A:")
            print(summarize_trajectory(
                pair["trajectory_a"]["states"], 
                pair["trajectory_a"]["actions"]
            ))
            
            print("\nTrajectory B:")
            print(summarize_trajectory(
                pair["trajectory_b"]["states"], 
                pair["trajectory_b"]["actions"]
            ))
            
            # Get input
            while True:
                choice = input("\nYour preference (0/1/s/q)? ").strip().lower()
                
                if choice == 'q':
                    print("\nSaving and quitting...")
                    dataset.save()
                    return
                elif choice == 's':
                    print("Skipping...")
                    break
                elif choice in ['0', '1']:
                    # Reconstruct tuples for the dataset manager
                    traj_a = (pair["trajectory_a"]["states"], pair["trajectory_a"]["actions"])
                    traj_b = (pair["trajectory_b"]["states"], pair["trajectory_b"]["actions"])
                    
                    dataset.add_preference(
                        traj_a=traj_a,
                        traj_b=traj_b,
                        preference=int(choice),
                        annotator_id=annotator_id
                    )
                    pairs_annotated += 1
                    print("✓ Saved preference.")
                    break
                else:
                    print("Invalid input. Please enter 0, 1, s, or q.")
                    
    except KeyboardInterrupt:
        print("\nInterrupted by user.")
        
    finally:
        dataset.save()
        print(f"\nAnnotation session complete. Added {pairs_annotated} new preferences.")
        print(f"Dataset now contains {len(dataset)} total preferences.")
        print(f"Saved to: {output_file}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="CLI for annotating RLHF trajectories.")
    parser.add_argument("--input", type=str, default="data/unannotated_pairs.json", help="Input JSON file with pairs")
    parser.add_argument("--output", type=str, default="data/human_preferences.json", help="Output dataset file")
    parser.add_argument("--annotator", type=str, default="human_tester", help="Annotator ID")
    
    args = parser.parse_args()
    
    annotate_cli(
        input_file=args.input,
        output_file=args.output,
        annotator_id=args.annotator
    )
