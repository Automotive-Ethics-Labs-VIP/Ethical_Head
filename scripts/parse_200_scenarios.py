ACTION_NAMES = {0: "maintain", 1: "swerve_left", 2: "swerve_right"}

def build_preference_pairs(scenarios, decisions, theory):
    """
    Build preference pairs in the exact format PreferenceDataset expects:
      trajectory_a = preferred action (A is always better, preference=0)
      trajectory_b = rejected action
    Two pairs per scenario (vs each of the two non-preferred actions).
    """
    import uuid, datetime
    pairs = []
    for sid, state in scenarios.items():
        preferred = decisions[sid][theory]
        for rejected in [0, 1, 2]:
            if rejected == preferred:
                continue
            pairs.append({
                "id": f"pref_{uuid.uuid4().hex[:8]}",
                "trajectory_a": {"states": [state], "actions": [preferred]},
                "trajectory_b": {"states": [state], "actions": [rejected]},
                "preference": 0,
                "annotator_id": "system",
                "timestamp": datetime.datetime.now().isoformat(),
                "scenario_id": sid,
                "theory": theory,
                "preferred_name": ACTION_NAMES[preferred],
                "rejected_name": ACTION_NAMES[rejected],
            })
    return pairs

